static uint8_t s_map[sizeof KBD + sizeof MOUSE + sizeof MEDIA + sizeof ABSP + sizeof GAMEPAD];

size_t hid_report_build(bool kbd, bool mouse, bool media, bool absp, bool gamepad, const uint8_t **out)
{
    size_t n = 0;
#define ADD(on, seg) if (on) { memcpy(s_map + n, seg, sizeof seg); n += sizeof seg; }
    ADD(kbd, KBD);
    ADD(mouse, MOUSE);
    ADD(media, MEDIA);
    ADD(absp, ABSP);
    ADD(gamepad, GAMEPAD);
#undef ADD
    *out = s_map;
    return n;
}
